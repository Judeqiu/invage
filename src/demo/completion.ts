const digest=(value:unknown)=>createHash('sha256').update(JSON.stringify(value)).digest('hex');
const time=(day:string)=>Date.parse(day+'T00:00:00Z');
const day=(value:number)=>new Date(value).toISOString().slice(0,10);
const money=(value:number)=>{if(!Number.isFinite(value))throw Error('Non-finite demo money');return value.toFixed(2);};
const rowId=(row:{sheet:string;row:number})=>JSON.stringify([row.sheet,row.row]);

/** Projection builders emit optional undefined properties and arithmetic -0.
 * Persist only present schema fields; reject unavailable numeric calculations.
 */
function generatedJson<T>(value:T):T {
  if(typeof value==='number'){
    if(!Number.isFinite(value))throw Error('Generated demo contains a non-finite calculation');
    return (Object.is(value,-0)?0:value) as T;
  }
  if(Array.isArray(value))return value.map(item=>{if(item===undefined)throw Error('Generated demo has an absent array item');return generatedJson(item);}) as T;
  if(value&&typeof value==='object')return Object.fromEntries(Object.entries(value).filter(([,v])=>v!==undefined).map(([k,v])=>[k,generatedJson(v)])) as T;
  return value;
}

/** Currency-cent allocation, preserving the supplied total exactly, including rebates. */
function allocate(amount:string,weights:number[]):string[] {
  const cents=Math.round(Number(amount)*100),sign=cents<0?-1:1,total=weights.reduce((a,b)=>a+b,0);
  if(!Number.isSafeInteger(cents)||!(total>0)||weights.some(w=>!Number.isFinite(w)||w<0))throw Error('Invalid demo allocation inputs');
  const exact=weights.map(w=>Math.abs(cents)*w/total),parts=exact.map(Math.floor);
  const order=exact.map((v,i)=>({i,r:v-parts[i]})).sort((a,b)=>b.r-a.r||a.i-b.i);
  for(let left=Math.abs(cents)-parts.reduce((a,b)=>a+b,0),i=0;left>0;left--,i++)parts[order[i].i]++;
  return parts.map(n=>money(sign*n/100));
}
function normalCdf(x:number):number {
  const z=Math.abs(x),t=1/(1+.2316419*z),density=Math.exp(-z*z/2)/Math.sqrt(2*Math.PI);
  const tail=density*t*(.319381530+t*(-.356563782+t*(1.781477937+t*(-1.821255978+t*1.330274429))));
  return x>=0?1-tail:tail;
}

/** Same rate/day-count convention as the existing dashboard probability model.
 * Historical realized volatility is a demo modeling input, never claimed as observed IV.
 */
export function demoOptionModel(spot:number,strike:number,expiry:string,at:string,iv:number,multiplier:number) {
  if(![spot,strike,multiplier].every(v=>Number.isFinite(v)&&v>0)||!Number.isFinite(iv)||iv<0)throw Error('Invalid demo model inputs');
  const years=(time(expiry)-time(at))/86400000/365,rate=.04,intrinsic=Math.max(strike-spot,0);
  if(years<=0)return{mark:Number(money(intrinsic*multiplier)),probability:Number(spot<strike)};
  const discounted=strike*Math.exp(-rate*years);
  if(iv===0)return{mark:Number(money(Math.max(intrinsic,discounted-spot)*multiplier)),probability:Number(spot<discounted)};
  const root=iv*Math.sqrt(years),d1=(Math.log(spot/strike)+(rate+iv*iv/2)*years)/root,d2=d1-root;
  const european=discounted*normalCdf(-d2)-spot*normalCdf(-d1);
  return {mark:Number(money(Math.max(intrinsic,european)*multiplier)),probability:normalCdf(-d2)};
}
function marketReader(book:DemoWorkbook,market:DemoMarketEvidence) {
  if(market.version!==1||market.sourceSha256!==book.source.sha256||market.asOf!==book.asOf)throw Error('Historical market evidence scope differs');
  if(market.series.some(s=>s.response.meta.currency!==book.currency))throw Error('Historical source currency differs from the approved demo');
  const series=new Map(market.series.map(s=>[s.symbol,s.response.quotes.map(q=>({date:q.date.slice(0,10),close:q.close,adjclose:q.adjclose}))
    .filter(q=>q.date<=book.asOf).sort((a,b)=>a.date.localeCompare(b.date))]));
  function bars(symbol:string,at:string){const rows=series.get(symbol)?.filter(q=>q.date<=at);if(!rows?.length||rows.some(q=>![q.close,q.adjclose].every(n=>Number.isFinite(n)&&n>0)))throw Error('Missing or invalid public-price evidence: '+symbol);return rows;}
  function latest(symbol:string,at:string){return bars(symbol,at).at(-1)!;}
  function volatility(symbol:string,at:string){
    const rows=bars(symbol,at);if(rows.length<3)throw Error('Not enough historical observations for demo calibration');
    const returns=rows.slice(1).map((q,i)=>Math.log(q.adjclose/rows[i].adjclose)),mean=returns.reduce((a,b)=>a+b,0)/returns.length;
    const variance=returns.reduce((sum,v)=>sum+(v-mean)**2,0)/(returns.length-1);
    const elapsedYears=(time(rows.at(-1)!.date)-time(rows[0].date))/86400000/365/returns.length;
    return Math.sqrt(variance/elapsedYears);
  }
  function previous(symbol:string,at:string){return latest(symbol,day(time(at)-86400000)).date;}
  function quote(symbol:string,strike:number,expiry:string,at:string){const iv=volatility(symbol,at),spot=latest(symbol,at).close;return{...demoOptionModel(spot,strike,expiry,at,iv,Number(book.multiplier)),iv,spot};}
  return{bars,latest,volatility,previous,quote,series};
}
function predecessorExpiry(at:string):string {
  const d=new Date(at+'T00:00:00Z');
  for(;;){const first=new Date(Date.UTC(d.getUTCFullYear(),d.getUTCMonth(),1)),friday=1+(5-first.getUTCDay()+7)%7+14;
    const expiry=day(Date.UTC(d.getUTCFullYear(),d.getUTCMonth(),friday));if(expiry>=at)return expiry;d.setUTCMonth(d.getUTCMonth()+1);}
}

/** Generate a complete scenario; never edits the original workbook or real accounts. */
export function prepareCompletedDemo(state:InvestorState,market:DemoMarketEvidence,plan:DemoCompletionPlan):InvestorState {
  const book=state.demo_workbook;
  if(state.profile.contact_email!=='demo@velovest.ai'||state.synthetic_demo?.version!==1||!book||Object.keys(state.broker_connections??{}).length)throw Error('Only the isolated worksheet demo can be completed');
  if(plan.version!==1||plan.sourceSha256!==book.source.sha256||plan.entries.length!==book.rows.length)throw Error('Reviewed plan must cover the complete source');
  const intents=new Map(plan.entries.map(e=>[rowId(e),e.kind]));
  if(intents.size!==book.rows.length||book.rows.some(r=>!['opening','roll'].includes(intents.get(rowId(r))!)))throw Error('Plan has duplicate or missing typed source intents');
  const source=marketReader(book,market),channels=[...new Set(book.rows.map(r=>r.channel))];
  const accounts=Object.fromEntries(channels.map(c=>[c,'demo:'+c]));
  const next=structuredClone(state);next.portfolio={};next.option_executions=[];
  delete next.option_identities;delete next.option_events;delete next.option_observations;delete next.option_journal;
  const completion:DemoCompletion={version:1,asOf:book.asOf,sourceSha256:book.source.sha256,marketSha256:digest(market),planSha256:digest(plan),
    methods:[DEMO_COMPLETION_NOTE,'Frozen at the workbook date. Only daily bars on or before each modeled valuation date are used.',
      'Volatility: sample log-return variance from the mirrored workbook-span calibration window, annualized by observed calendar elapsed time.',
      'Option marks: European Black–Scholes with intrinsic-value floor; existing dashboard illustrative rate convention, no dividend adjustment. This is not an observed option quote.',
      'A prior completed short-put cycle is generated per worksheet row using preceding observed trading days and the next standard monthly expiry. Roll predecessors are modeled, not reconstructed broker legs.',
      'Opening rows use worksheet credit minus debit; roll replacement opening credit is modeled and its closing debit preserves combined worksheet cash. Worksheet fee cash is conserved at currency-cent precision; original Excel numeric text remains retained.',
      'Cash and generated reserve assets are allocated by current put assignment notional using largest remainders. Reserve assets balance the supplied NAV; they are fictional funding, not stock backing or broker margin.',
      'All premium/fees, realized and unrealized P&L and option-only expiry loss use the normal shared calculations. No original headline premium/earnings/risk overrides survive.'],
    accounts,equityPrices:{},quotes:{},entrySpots:{},executionSources:{},rollFills:[],snapshots:[],reserves:{},initialCash:{}};
  for(const row of book.rows){
    const kind=intents.get(rowId(row))!,quantity=Number(row.contracts),strike=Number(row.strike),multiplier=Number(book.multiplier);
    if(!(quantity>0&&strike>0&&multiplier>0))throw Error('Current demo puts need positive contract terms');
    const currentKey='DEMO-'+digest([book.source.sha256,row.sheet,row.row]).slice(0,16)+'@'+row.channel;
    const closed=kind==='roll'?row.entryDate:source.previous(row.underlying,row.entryDate),opened=source.previous(row.underlying,closed);
    const oldExpiry=predecessorExpiry(closed);
    if(oldExpiry>=row.expiry)throw Error('Generated predecessor must expire before the worksheet replacement');
    const oldOpen=source.quote(row.underlying,strike,oldExpiry,opened),oldClose=source.quote(row.underlying,strike,oldExpiry,closed);
    const current=source.quote(row.underlying,strike,row.expiry,row.entryDate),asof=source.quote(row.underlying,strike,row.expiry,book.asOf);
    const worksheetCash=addDecimals(row.credit,negateDecimal(row.debit)),fee=money(Number(row.fees));
    const openingCash=kind==='roll'?money(current.mark*quantity):money(Number(worksheetCash));
    if(Number(openingCash)<0)throw Error('An opening source intent has debit cash; review the typed plan');
    const closeCash=kind==='roll'?addDecimals(worksheetCash,negateDecimal(openingCash)):money(-oldClose.mark*quantity);
    if(Number(closeCash)>0)throw Error('Modeled roll closing debit cannot reconcile to the source cash');
    const fees=kind==='roll'?allocate(fee,[quantity,quantity]):[fee,fee];
    const prefix='demo:'+digest([book.source.sha256,row.sheet,row.row]).slice(0,20),parent=prefix+':roll';
    const add=(suffix:string,date:string,clock:string,expiry:string,side:'buy'|'sell',effect:'open'|'close',gross:string,feeCash:string,origin:'worksheet_interpretation'|'modeled',order:string)=>{
      const execution:OptionExecution={channel:row.channel,account_id:accounts[row.channel],execution_id:prefix+':'+suffix,
        contract_id:JSON.stringify([row.underlying,expiry,row.strike,'put']),executed_at:date+'T'+clock,underlying:row.underlying,
        right:'put',expiry,strike:row.strike,multiplier:book.multiplier,contracts:row.contracts,side,effect,currency:book.currency,
        gross_premium:gross,commission:negateDecimal(feeCash)};
      next.option_executions!.push(execution);completion.executionSources[execution.execution_id]={origin,sheet:row.sheet,row:row.row,description:row.description};
      completion.rollFills.push({id:execution.execution_id,order,parent:order,prefix:order,account:execution.account_id,
        contract:{underlying:row.underlying,right:'put',expiry,strike:row.strike,multiplier:book.multiplier,currency:book.currency},
        at:execution.executed_at,clock:'Fictional demo clock; not a broker timestamp',quantity:row.contracts,side,effect,cash:addDecimals(gross,execution.commission!),
        gross_cash:gross,basis:'net',terminal:false,source:{id:'generated-demo-ledger',version:completion.marketSha256}});
    };
    add('predecessor-open',opened,'15:30:00',oldExpiry,'sell','open',money(oldOpen.mark*quantity),kind==='roll'?fees[0]:fee,'modeled',prefix+':history-open');
    add('predecessor-close',closed,'15:45:00',oldExpiry,'buy','close',closeCash,kind==='roll'?fees[0]:fee,'modeled',kind==='roll'?parent:prefix+':history-close');
    add('current-open',row.entryDate,'16:00:00',row.expiry,'sell','open',openingCash,kind==='roll'?fees[1]:fee,kind==='roll'?'modeled':'worksheet_interpretation',kind==='roll'?parent:prefix+':current');
    next.portfolio![currentKey]={instrument:'option',currency:book.currency,channel:row.channel,units:quantity,avg_price:Number(openingCash)/quantity,
      option:{underlying:row.underlying,right:'put',side:'short',strike,expiry:row.expiry,multiplier,settlement:'physical',mark:asof.mark,quote_source:'manual',underlying_mark:asof.spot}};
    completion.equityPrices[row.underlying]=asof.spot;
    completion.quotes[currentKey]={mark:asof.mark,probability:{source:'demo_historical_volatility',asOf:book.asOf,iv:asof.iv,probability:asof.probability,method:'Modeled from historical daily stock returns; not observed implied volatility'}};
    const entry=source.latest(row.underlying,row.entryDate);completion.entrySpots[currentKey]={price:entry.adjclose,date:entry.date,basis:'adjusted_close'};
  }
  next.option_executions=mergeOptionExecutions([],next.option_executions!);
  const weights=channels.map(channel=>book.rows.filter(r=>r.channel===channel).reduce((n,r)=>n+Number(r.contracts)*Number(r.strike)*Number(book.multiplier),0));
  const cashParts=allocate(book.summary.cash,weights);
  next.cash=channels.map((channel,i)=>({channel,currency:book.currency,amount:Number(cashParts[i]),updated_at:book.asOf}));
  const optionValue=Object.values(next.portfolio!).reduce((n,h)=>n-h.units*h.option!.mark,0),reserve=addDecimals(book.summary.nav,negateDecimal(book.summary.cash),negateDecimal(money(optionValue)));
  if(Number(reserve)<0)throw Error('Supplied NAV cannot support a positive reserve asset with the retained cash/positions');
  const reserves=allocate(reserve,weights);
  for(const[channel,i]of channels.map((c,i)=>[c,i]as const)){
    completion.reserves[channel]=Number(reserves[i]);
    next.portfolio!['DEMO-RESERVE@'+channel]={instrument:'fund',channel,currency:book.currency,units:1,avg_price:Number(reserves[i]),
      fund:{quote_source:'manual',mark:Number(reserves[i]),name:'Generated demo reserve'}};
    const cashFlow=addDecimals('0',...next.option_executions.filter(e=>e.channel===channel).map(e=>addDecimals(e.gross_premium,e.commission!)));
    completion.initialCash[channel]=addDecimals(cashParts[i],negateDecimal(cashFlow));
  }
  next.demo_completion=completion;
  // Recreate daily holdings/cash from the same complete fictional execution ledger.
  const first=next.option_executions.map(e=>e.executed_at.slice(0,10)).sort()[0];
  const dates=[...new Set(market.series.flatMap(s=>s.response.quotes.map(q=>q.date.slice(0,10))))].filter(d=>d>=first&&d<=book.asOf).sort();
  for(const at of dates){
    const portfolio:Record<string,Holding>=Object.fromEntries(Object.entries(next.portfolio!).filter(([,h])=>h.instrument==='fund'));
    const inventory=new Map<string,{execution:OptionExecution;quantity:number}>();
    const fills=next.option_executions.filter(e=>e.executed_at.slice(0,10)<=at).sort((a,b)=>a.executed_at.localeCompare(b.executed_at));
    for(const e of fills){const key=JSON.stringify([e.channel,e.contract_id]),prior=inventory.get(key);
      if(e.effect==='open')inventory.set(key,{execution:e,quantity:(prior?.quantity??0)+Number(e.contracts)});
      else{if(!prior||prior.quantity<Number(e.contracts))throw Error('Generated history cannot close an absent lot');prior.quantity-=Number(e.contracts);}}
    for(const[key,lot]of inventory)if(lot.quantity){const e=lot.execution,q=source.quote(e.underlying,Number(e.strike),e.expiry,at);
      const currentKey:string|undefined=Object.entries(next.portfolio!).find(([,h])=>h.option&&h.channel===e.channel&&h.option.underlying===e.underlying&&h.option.expiry===e.expiry&&h.option.strike===Number(e.strike))?.[0];
      const snapshotKey=currentKey??'DEMO-HISTORY-'+digest(key).slice(0,16)+'@'+e.channel;
      portfolio[snapshotKey]={instrument:'option',channel:e.channel,currency:e.currency,units:lot.quantity,avg_price:Number(e.gross_premium)/Number(e.contracts),
        option:{underlying:e.underlying,right:e.right,side:'short',strike:Number(e.strike),expiry:e.expiry,multiplier:Number(e.multiplier),settlement:'physical',quote_source:'manual',mark:q.mark,underlying_mark:q.spot}};}
    const cashes:CashBalance[]=channels.map(channel=>({channel,currency:book.currency,updated_at:at,amount:Number(addDecimals(completion.initialCash[channel],...fills.filter(e=>e.channel===channel).map(e=>addDecimals(e.gross_premium,e.commission!))))}));
    const live=buildLivePositions(portfolio,{},undefined,cashes,null,at,undefined,{reportingCurrency:book.currency,allowEmpty:true});
    for(const p of live.positions)if(p.option){const q=source.quote(p.option.underlying,p.option.strike,p.option.expiry,at);
      p.demoProbability={source:'demo_historical_volatility',asOf:at,iv:q.iv,probability:q.probability,method:'Modeled from historical daily stock returns; not observed implied volatility'};}
    completion.snapshots.push(generatedJson({...live,date:at,positions:live.positions.map(p=>({...p,markSource:'manual' as const})),
      cashAmount:live.cashAmount??undefined,cashCurrency:live.cashCurrency??undefined,cashChannel:live.cashChannel??undefined,
      depositsCurrency:live.depositsCurrency??undefined,reportingCurrency:book.currency,brokerAsOf:Object.fromEntries(channels.map(c=>[c,at]))}));
  }
  return next;
}

export function demoRelationships(state:InvestorState,filters:{channel?:string;asOf?:string;from?:string;to?:string;evidence?:string;q?:string}={}) {
  const c=completedDemo(state);if(!c)throw Error('No completed demo');
  const groups=[],coverage=[],connections=[];
  for(const[channel,account]of Object.entries(c.accounts)){
    if(filters.channel&&filters.channel!==channel)continue;
    const rows=c.rollFills.filter(f=>f.account===account),broker=state.demo_workbook!.rows.find(r=>r.channel===channel)!.brokerId;
    const relationships=buildOptionRelationships(broker,channel,account,rows).filter(r=>(!filters.asOf||r.through.slice(0,10)<=filters.asOf)&&
      (!filters.from||r.at.slice(0,10)>=filters.from)&&(!filters.to||r.through.slice(0,10)<=filters.to)&&(!filters.evidence||r.evidence===filters.evidence)&&
      (!filters.q||[r.old.underlying,r.old.strike,r.old.expiry,r.replacement.strike,r.replacement.expiry].join(' ').toUpperCase().includes(filters.q.toUpperCase())));
    for(const r of relationships)r.reason='Generated demo roll: '+r.reason;
    groups.push(...groupOptionRelationships(relationships,rows));
    coverage.push({channel,broker_id:broker,account_id:account,label:channel+' · generated demo',archives:0,history_available:true,first_trade:rows.map(r=>r.at).sort()[0]??null,last_trade:rows.map(r=>r.at).sort().at(-1)??null});
    connections.push({channel,broker_id:broker,account_id:account,label:channel+' · generated demo'});
  }
  return{groups,spreads:[],historyGaps:[],coverage,gaps:[],as_of:c.asOf,connections};
}
export function completedDemoDashboard(state:InvestorState):DashboardPayload {
  const c=completedDemo(state);if(!c)throw Error('No completed demo');
  const live=buildLivePositions(state.portfolio??{},c.equityPrices,undefined,state.cash,null,c.asOf,undefined,{reportingCurrency:state.demo_workbook!.currency});
  for(const p of live.positions)if(c.quotes[p.ticker]){p.brokerMark=c.quotes[p.ticker].mark;p.demoProbability=c.quotes[p.ticker].probability;}
  const details=openOptionTradeDetails(state.portfolio??{},state.option_executions,c.accounts),relationships=demoRelationships(state);
  attachLatestRollPremium(state.portfolio??{},details,relationships.groups.flatMap(g=>g.relationships),c.accounts);
  for(const[key,value]of Object.entries(details))value.entrySpot=c.entrySpots[key];
  const journal=buildExecutionJournal(state.option_executions),channels=Object.keys(c.accounts);
  live.issues.push({code:'demo_completion',severity:'warning',message:DEMO_COMPLETION_NOTE});
  return{slug:state.user.id,displayName:state.profile.display_name,generatedAt:c.asOf+'T00:00:00Z',empty:false,
    model:buildDashboardModel(live,c.snapshots),benchmark:null,equityPrices:c.equityPrices,
    premiumJournal:{available:true,daily:journal.daily,channels},premiumSupportedChannels:channels,
    optionTradeDetails:details,optionAnalytics:buildRecordedOptionAnalytics(state.option_executions),
    productProfile:'consultant',productName:'Velovest',brokerAsOf:Object.fromEntries(channels.map(ch=>[ch,c.asOf])),
    brokerChannels:Object.fromEntries(state.demo_workbook!.rows.map(row=>[row.channel,{brokerId:row.brokerId,label:row.sheet}])),
    demoCompletion:{asOf:c.asOf,note:DEMO_COMPLETION_NOTE,methods:c.methods,marketSha256:c.marketSha256},warnings:live.issues};
}

/** A complete generated ledger establishes zero for an empty period, not an unknown result. */
export function applyCompletedDemoScopes(payload:DashboardPayload,scopes:Record<string,Record<string,any>>) {
  if(!payload.demoCompletion)return;
  for(const[dateKey,channels]of Object.entries(scopes))for(const[channel,scope]of Object.entries(channels)){
    const date=dateKey==='live'?payload.demoCompletion.asOf:dateKey;
    const owns=(row:{channel:string})=>channel==='merged' ? scope.view.channels.includes(row.channel) : row.channel===channel;
    const fills=(payload.optionAnalytics?.executions??[]).filter(e=>owns(e)&&e.executed_at.slice(0,10)<=date);
    for(const key of ['daily','mtd','total','fees','totalFees'])if(scope.premium[key]===null)scope.premium[key]=0;
    for(const[from,result]of Object.entries(scope.realized) as Array<[string,{value:number|null;reason:string}]>){
      const profits=(payload.optionAnalytics?.profits??[]).filter(r=>owns(r)&&r.date>=from&&r.date<=date);
      if(!profits.length&&result.value===null)result.value=0;
      result.reason='Generated demo completed cycles · After fees · As of '+date;
    }
    scope.premium.reason='Generated demo option cash flow · Before fees';
    scope.premium.totalReason=scope.premium.reason;
    scope.demoSource={asOf:date,executions:fills.length,note:DEMO_COMPLETION_NOTE};
  }
}
