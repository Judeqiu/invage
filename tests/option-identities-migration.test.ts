import { expect, it } from 'vitest';
import { createInvestorFixture, useTestDatabase } from './helpers/database.js';
import { tradesFixture, optionFill } from './helpers/trades-fixture.js';
import { buildOptionIdentityIndex } from '../src/brokers/option-identities.js';
import { loadInvestor, saveInvestor, saveOptionJournalMetadata } from '../src/state/investor-store.js';
import { migrateBooks } from '../src/books/migrate.js';
import { ensureBooksSeeded } from '../src/books/service.js';
import { getPool } from '../src/books/db.js';

await useTestDatabase({books:true});
it('persists the additive migration atomically, leaves financial journals unchanged and rejects a stale writer', async () => {
  await migrateBooks();
  const fixture = tradesFixture();
  await createInvestorFixture(fixture);
  await ensureBooksSeeded(fixture);
  const journalCount = async () => (await getPool().query('SELECT count(*)::int AS n FROM journal_entries')).rows[0].n;
  const before = await journalCount();
  const snapshot = await loadInvestor(fixture.user.id), stale = await loadInvestor(fixture.user.id);
  snapshot.state.option_identities = buildOptionIdentityIndex(snapshot.state);
  await saveOptionJournalMetadata(snapshot);
  const migrated = await loadInvestor(fixture.user.id);
  const {option_identities,...rest} = migrated.state;
  expect(rest).toEqual(fixture);
  expect(option_identities).toEqual(buildOptionIdentityIndex(fixture));
  expect(await journalCount()).toBe(before);
  expect(buildOptionIdentityIndex(migrated.state)).toEqual(option_identities);
  stale.state.option_executions!.push(optionFill({execution_id:'concurrent'}));
  await expect(saveInvestor(stale)).rejects.toThrow(/changed|revision/i);
  expect(await loadInvestor(fixture.user.id)).toEqual(migrated);
  migrated.state.option_executions!.push(optionFill({execution_id:'later-import',executed_at:'2026-10-03T10:00:00'}));
  await saveInvestor(migrated);
  const imported = await loadInvestor(fixture.user.id);
  expect(Object.keys(imported.state.option_identities!.executions)).toHaveLength(3);
  expect(await journalCount()).toBe(before);
  const pk = Object.values(imported.state.option_identities!.options)[0];
  imported.state.option_journal = {[pk]:{thesis:'Wheel thesis',updated_at:'2026-10-20T10:00:00Z'}};
  await saveOptionJournalMetadata(imported);
  expect((await loadInvestor(fixture.user.id)).state.option_journal?.[pk].thesis).toBe('Wheel thesis');
  expect(await journalCount()).toBe(before);
});
it('does not seed an empty ledger and refuses a financial edit through the metadata path', async () => {
  const fixture = tradesFixture(); fixture.user.id = 'b648d3d4-f46f-4979-a9f3-7d76cefa9d15';
  await createInvestorFixture(fixture);
  const snapshot = await loadInvestor(fixture.user.id);
  await saveOptionJournalMetadata(snapshot);
  expect((await getPool().query('SELECT count(*)::int AS n FROM journal_entries WHERE household_id=$1',[fixture.user.id])).rows[0].n).toBe(0);
  snapshot.state.portfolio!['AAPL-put'].units = 99;
  await expect(saveOptionJournalMetadata(snapshot)).rejects.toThrow(/cannot change/);
  expect((await loadInvestor(fixture.user.id)).state.portfolio!['AAPL-put'].units).toBe(1);
});
