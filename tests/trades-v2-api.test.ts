import { persistPortfolioFixture } from './helpers/portfolio-projection.js';
import { expect, it, vi } from 'vitest';
import express from 'express';
import request from 'supertest';
import { tradesFixture } from './helpers/trades-fixture.js';
const mocks = vi.hoisted(() => ({ load:vi.fn(), save:vi.fn(), history:vi.fn(), relationships:vi.fn() }));
vi.mock('../src/state/investor-store.js',() => ({loadInvestor:mocks.load,saveInvestor:mocks.save,saveOptionJournalMetadata:mocks.save}));
vi.mock('../src/webapp/option-history-data.js',() => ({optionHistoryForState:mocks.history}));
vi.mock('../src/webapp/option-relationships-data.js',() => ({optionRelationshipsForState:mocks.relationships}));
import { createDashboardApiRouter } from '../src/webapp/dashboard-api.js';

it('requires authentication, isolates cached journals by owner/revision, and keeps GETs read-only', async () => {
  const a = tradesFixture(), b = {...tradesFixture(),user:{...a.user,id:'a648d3d4-f46f-4979-a9f3-7d76cefa9d15'},portfolio:{}};
  let revision = 1;
  mocks.load.mockImplementation(async owner => ({state:structuredClone(owner === a.user.id ? a : b),revision}));
  mocks.history.mockReturnValue({observations:[],gaps:[],events:[],episodes:[]});
  mocks.relationships.mockReturnValue({groups:[],spreads:[],historyGaps:[],coverage:[],gaps:[],connections:[],as_of:null});
  await persistPortfolioFixture(a);
  await persistPortfolioFixture(b);
  mocks.history.mockClear();
  const app = express(); app.use(express.json());
  app.use((req,_res,next) => {if (req.headers['x-owner']) (req as any).user = {userId:req.headers['x-owner']};next();});
  app.use(createDashboardApiRouter());
  await request(app).get('/trades-v2').expect(401);
  expect(mocks.load).not.toHaveBeenCalled();
  const first = await request(app).get('/trades-v2').set('x-owner',a.user.id).expect(200);
  expect(first.headers['cache-control']).toBe('private, no-store');
  expect(first.body.rows).toHaveLength(1);
  const second = await request(app).get('/trades-v2').set('x-owner',b.user.id).expect(200);
  expect(second.body.rows).toHaveLength(0);
  expect(mocks.history).not.toHaveBeenCalled();
  const pk = first.body.rows[0].optionId;
  revision++;
  a.portfolio!['AAPL-put'].units = 2;
  await persistPortfolioFixture(a);
  mocks.history.mockClear();
  const updated = await request(app).get('/trades-v2').set('x-owner',a.user.id).expect(200);
  expect(updated.body.rows[0]).toMatchObject({contracts:'2',premium:null,optionId:pk});
  expect(a.option_identities).toBeUndefined();
  expect(mocks.save).not.toHaveBeenCalled();
  await request(app).get('/trades-v2/history').set('x-owner',a.user.id).expect(200);
  await request(app).get('/trades-v2/history').set('x-owner',a.user.id).expect(200);
  expect(mocks.history).not.toHaveBeenCalled();
  await request(app).get('/trades-v2/history?refresh=1').set('x-owner',a.user.id).expect(200);
  expect(mocks.history).not.toHaveBeenCalled();
  mocks.save.mockImplementation(async snapshot => {snapshot.revision++;});
  await request(app).put(`/trades-v2/${pk}/note`).send({text:'Thesis',revision}).expect(401);
  await request(app).put(`/trades-v2/${pk}/note`).set('x-owner',a.user.id).send({text:'x'.repeat(8001),revision}).expect(400);
  await request(app).put(`/trades-v2/${pk}/note`).set('x-owner',b.user.id).send({text:'Wrong account',revision}).expect(404);
  await request(app).put(`/trades-v2/${pk}/note`).set('x-owner',a.user.id).send({text:'Stale',revision:revision-1}).expect(409);
  const saved = await request(app).put(`/trades-v2/${pk}/note`).set('x-owner',a.user.id).send({text:'Thesis <test>',revision}).expect(200);
  expect(saved.body).toMatchObject({text:'Thesis <test>',revision:revision+1});
  expect(mocks.save).toHaveBeenCalledTimes(1);
  expect(mocks.save.mock.calls[0][0].state.option_journal[pk].thesis).toBe('Thesis <test>');
});
